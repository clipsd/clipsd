"""Make a preview ("проба") copy of the sources: the owner's own test of install and update before
the real update channel exists.

    python3 packaging/preview_build.py OUT_DIR [--version 2.0.1] [--public-key B64]

1. copies the project into OUT_DIR (a new folder; no .git, builds, virtual environments, test output);
2. with --version: writes it into clipshot/__init__.py and runs packaging/stamp_version.py there;
3. writes OUT_DIR/clipshot/_preview_build.py: PREVIEW = True and the public key of the proba channel
   (--public-key, else packaging/proba-public-key.txt; a placeholder is refused).

Then build in OUT_DIR as usual: packaging/linux/build_linux.sh (archive ClipSD-<v>-proba-linux-x86_64.tar.gz)
or packaging/stage_windows.py + build.ps1 (GitHub Actions, manual run with "preview").
The repository itself is never changed: clipshot/_preview_build.py is in .gitignore, release.sh
refuses to run while it exists, tools/release_check.py fails a tree that has it.
"""

import argparse
import base64
import binascii
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KEY_FILE = ROOT / "packaging" / "proba-public-key.txt"
MODULE = Path("clipshot") / "_preview_build.py"
IGNORE = shutil.ignore_patterns(".git", "dist", "dist-*", "winbuild", ".venv*", "__pycache__", "*.pyc", "output",
                                "_preview_build.py")
_VERSION_RE = re.compile(r"^[0-9]{1,4}\.[0-9]{1,4}\.[0-9]{1,4}$")


class PreviewError(Exception):
    pass


def read_key(text: str) -> str:
    """The proba public key: base64 of 32 raw bytes (printed by tools/channel_sign.py keygen)."""
    key = (text or "").strip()
    try:
        raw = base64.b64decode(key, validate=True)
    except (binascii.Error, ValueError):
        raw = b""
    if len(raw) != 32:
        raise PreviewError("the proba public key is missing or a placeholder: run "
                           "tools/channel_sign.py keygen --private ~/.config/clipsd-dev/proba-channel.key "
                           "and put the printed key into packaging/proba-public-key.txt")
    return key


def key_from_file(path: Path = KEY_FILE) -> str:
    lines = [ln.strip() for ln in path.read_text(encoding="utf-8").splitlines()
             if ln.strip() and not ln.lstrip().startswith("#")]
    return lines[0] if lines else ""


def module_text(public_key: str) -> str:
    return ("# Generated by packaging/preview_build.py: this is a PREVIEW build (the owner's own tests).\n"
            "# Never commit this file and never release a build that has it.\n"
            "PREVIEW = True\n"
            f"PROBA_PUBLIC_KEYS = ({public_key!r},)\n")


def make(out: Path, version: str = "", public_key: str = "") -> Path:
    out = Path(out).resolve()
    if out.exists() and any(out.iterdir()):
        raise PreviewError(f"{out} exists and is not empty")
    if out == ROOT or ROOT in out.parents:
        raise PreviewError("the preview copy must be outside the project folder")
    key = read_key(public_key or key_from_file())
    if version and not _VERSION_RE.match(version):
        raise PreviewError(f"version must look like 2.0.1, got {version!r}")
    shutil.copytree(ROOT, out, ignore=IGNORE, dirs_exist_ok=True)
    if version:
        init = out / "clipshot" / "__init__.py"
        text = init.read_text(encoding="utf-8")
        init.write_text(re.sub(r'^__version__ = "[^"]+"', f'__version__ = "{version}"', text, flags=re.M),
                        encoding="utf-8")
        subprocess.run([sys.executable, str(out / "packaging" / "stamp_version.py")], check=True, cwd=out)
    (out / MODULE).write_text(module_text(key), encoding="utf-8")
    return out


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("out")
    parser.add_argument("--version", default="")
    parser.add_argument("--public-key", default="")
    args = parser.parse_args(argv)
    try:
        out = make(Path(args.out), args.version, args.public_key)
    except (PreviewError, OSError, subprocess.CalledProcessError) as exc:
        print(f"preview_build: {exc}", file=sys.stderr)
        return 2
    print(f"preview_build: preview sources in {out} (proba channel, {MODULE})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
